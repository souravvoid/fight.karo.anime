export function maxHealthFor(def: FighterDef): number {
  return 100 + (def.stats.health - 8) * 4;
}

export function walkSpeedFor(def: FighterDef): number {
  return 190 + def.stats.speed * 11;
}

export function powerScaleFor(def: FighterDef): number {
  return 0.86 + def.stats.power * 0.028;
}
